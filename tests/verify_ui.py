"""Browser regression checks. Run a local HTTP server, then python3 tests/verify_ui.py.
Requires playwright and its Chromium browser.
"""
import asyncio, json, os, tempfile, shutil
from pathlib import Path
from playwright.async_api import async_playwright

async def main():
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True, executable_path=shutil.which('chromium') or None)
        page = await browser.new_page(viewport={"width": 1440, "height": 1000})
        errors=[]
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.on('dialog', lambda dialog: dialog.accept())
        await page.goto(os.environ.get('IELTS_TEST_URL', 'http://127.0.0.1:8000'))
        await page.evaluate("localStorage.setItem('ielts-gate','1');document.documentElement.classList.remove('locked')")
        await page.wait_for_selector('#lesson1 .step-tabs',state='attached')
        result=await page.evaluate('''() => {
          let editions=0, paragraphs=0, exercises=0;
          for(const a of DATA.articles){
            const type=a.type==='小作文'?'task1':'task2';
            for(const edition of ['nine','seven']){
              if(!a.meta[edition+'_complete'])continue;
              state[type]=a.id;state.version[a.id]=edition;
              const ps=paras(a);editions++;paragraphs+=ps.length;
              const target=document.getElementById(type==='task1'?'lesson1':'lesson2');
              for(const step of ['read','cloze','translate','transfer']){
                state.step=step;renderLesson(type);
                const content=target.querySelector('#stepContent');
                const blocks=[...content.querySelectorAll(step==='read'?'.modelp':step==='transfer'?'[data-transfer-item]':'.clozebox')];
                if(step!=='transfer' && blocks.length!==ps.length)throw Error(`${a.id}/${edition}/${step} missing paragraphs`);
                if(step==='read')blocks.forEach((b,i)=>{if(b.querySelector('p.en').textContent!==ps[i].en)throw Error('Read text changed')});
                if(step==='cloze')blocks.forEach((b,i)=>{
                  const text=b.querySelector('p.en').cloneNode(true);
                  text.querySelectorAll('input').forEach(input=>input.replaceWith(input.dataset.answer));
                  if(text.textContent!==ps[i].en)throw Error(`${a.id}/${edition}/${i} cloze text incomplete`);
                  if(!b.querySelector('input'))throw Error('Paragraph has no cloze');
                });
                if(step==='translate')blocks.forEach((b,i)=>{
                  if(b.querySelector('.translation-cn').textContent!==ps[i].cn)throw Error('Chinese text changed');
                  if(b.querySelector('.answer .en').textContent!==ps[i].en)throw Error('Translation answer incomplete');
                });
                if(step==='transfer'){
                  if(blocks.length<3)throw Error(`${a.id}/${edition} no transfer exercises`);
                  exercises+=blocks.length;
                  blocks.forEach(b=>{if(!b.querySelector('textarea')||!b.querySelector('.answer .en').textContent)throw Error('Missing exercise fields')});
                }
                if(type==='task1' && !target.querySelector('input[type=file]'))throw Error('Missing chart upload');
                if(type==='task2' && target.querySelector('.chart-box'))throw Error('Chart on Task2');
              }
            }
          }
          state.task1='t1-31';state.version['t1-31']='nine';state.step='read';renderLesson('task1');go('task1');
          return {editions,paragraphs,exercises};
        }''')
        # Drafts and cloze answers survive module switches and page reloads.
        await page.evaluate("setStep('cloze','task1')")
        await page.locator('#lesson1 input[data-cloze]').first.fill('saved cloze')
        await page.evaluate("setStep('translate','task1')")
        await page.locator('#lesson1 textarea').last.fill('saved final paragraph')
        await page.evaluate("setStep('transfer','task1')")
        await page.locator('#lesson1 textarea').first.fill('saved transfer answer')
        await page.locator('#lesson1 [data-transfer-item] button').first.click()
        assert await page.locator('#lesson1 [data-transfer-item] .answer').first.is_visible()
        await page.evaluate("setStep('translate','task1')")
        assert await page.locator('#lesson1 textarea').last.input_value()=='saved final paragraph'
        # Use a valid small image generated by the browser itself.
        png=await page.evaluate("() => {const c=document.createElement('canvas');c.width=400;c.height=180;const ctx=c.getContext('2d');ctx.fillStyle='#edf4ef';ctx.fillRect(0,0,400,180);ctx.fillStyle='#284e40';ctx.font='22px sans-serif';ctx.fillText('Test chart 1976 / 2011',30,90);return c.toDataURL('image/png').split(',')[1]}")
        import base64
        await page.locator('#chart-file-t1-31').set_input_files({"name":"test-chart.png","mimeType":"image/png","buffer":base64.b64decode(png)})
        await page.wait_for_selector('#chart-preview-t1-31 img')
        await page.evaluate("state.task1='t1-01';renderLesson('task1')")
        assert await page.locator('#chart-preview-t1-01 img').count()==0
        await page.evaluate("state.task1='t1-31';renderLesson('task1')")
        await page.wait_for_selector('#chart-preview-t1-31 img')
        await page.reload();await page.wait_for_selector('#lesson1 .step-tabs',state='attached')
        await page.evaluate("state.task1='t1-31';state.step='translate';renderLesson('task1');go('task1')")
        await page.wait_for_selector('#chart-preview-t1-31 img')
        assert await page.locator('#lesson1 textarea').last.input_value()=='saved final paragraph'
        await page.evaluate("setStep('transfer','task1')")
        assert await page.locator('#lesson1 textarea').first.input_value()=='saved transfer answer'
        # Export includes images; remove and import must restore the same image and drafts.
        async with page.expect_download() as dl:
            await page.evaluate('exportBackup()')
        download=await dl.value
        with tempfile.TemporaryDirectory() as tmp:
            backup=Path(tmp)/'backup.json';await download.save_as(backup)
            payload=json.loads(backup.read_text());assert len(payload['charts'])==1
            await page.evaluate("removeChart('t1-31')")
            await page.wait_for_selector('#chart-preview-t1-31 img',state='detached')
            await page.locator('#importBackup').set_input_files(backup)
            await page.wait_for_selector('#chart-preview-t1-31 img')
        # Invalid types do not replace an existing chart.
        await page.locator('#chart-file-t1-31').set_input_files({"name":"bad.svg","mimeType":"image/svg+xml","buffer":b'<svg></svg>'})
        await page.wait_for_function("document.getElementById('chart-status-t1-31').textContent.includes('上传失败')")
        assert await page.locator('#chart-preview-t1-31 img').count()==1
        # Mobile layout: upload box and training controls remain inside the viewport.
        await page.set_viewport_size({"width":390,"height":844})
        await page.evaluate("setStep('cloze','task1')")
        assert await page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile horizontal overflow'
        assert not errors, errors
        print(json.dumps({**result,'chart_upload_reload_isolation_backup_restore':'passed','draft_persistence':'passed','mobile':'passed','page_errors':errors},ensure_ascii=False))
        await browser.close()

asyncio.run(main())
